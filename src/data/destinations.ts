/**
 * 兼容全部城市：先查手工精修的 16 个，再查国内 388 个地级市。
 * 找不到才返回 undefined（调用方必须用 `?.` 或默认值处理）。
 */
export function getDestination(id: string): Destination | undefined {
  const curated = DESTINATIONS.find((d) => d.id === id);
  if (curated) return { ...curated, handbook: HANDBOOKS[curated.id] };
  const cn = CN_CITIES.find((c) => c.id === id);
  return cn ? cnCityToDestination(cn) : undefined;
}
